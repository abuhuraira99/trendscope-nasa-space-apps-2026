/** One-line reference in author-year style. */
export function citation(source: Source): string {
  const year = source.year !== undefined ? ` (${source.year})` : "";
  const venue = source.venue ? ` ${source.venue}.` : "";
  const link = source.doi ? ` https://doi.org/${source.doi}` : ` ${source.url}`;
  const accessed = source.accessed && !source.doi ? ` Accessed ${source.accessed}.` : "";
  return `${source.authors}${year}. ${source.title}.${venue}${link}${accessed}`;
}

/** Short in-text label: "Mann 1945", "Yue and Wang 2004", "Gelaro et al. 2017". */
export function shortCite(source: Source): string {
  const a = source.authors;
  // Family names are the parts followed by ", " and initials, e.g. "Wang, C." or "Yuan, D.-N.".
  const families = Array.from(
    a.matchAll(/(?:^|,\s(?:and\s)?|\sand\s)([^,]+?),\s(?:[A-ZÀ-ÖØ-Þ][a-z]?\.[\s-]?)+/g),
    (m) => (m[1] ?? "").trim(),
  ).filter((f) => f.length > 0);
  let who: string;
  if (families.length === 0) who = a;
  else if (/et al\./.test(a) || families.length > 2) who = `${families[0] ?? a} et al.`;
  else if (families.length === 2) who = `${families[0] ?? a} and ${families[1] ?? ""}`;
  else who = families[0] ?? a;
  return source.year !== undefined ? `${who} ${source.year}` : who;
}
